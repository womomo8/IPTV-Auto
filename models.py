
"""Shared data models for the IPTV pipeline.

This module is the single source of truth for data structures exchanged
between project programs. Other modules must import these types instead
of defining duplicate interface structures.

Interface changes must be reviewed and recorded before modification.
"""

from dataclasses import dataclass
from enum import Enum, IntEnum
from typing import Optional, Tuple


# ---------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------


class SourceKind(str, Enum):
    """Origin category of a source or candidate."""

    MANUAL_STREAM = "manual_stream"
    MANUAL_SUBSCRIPTION = "manual_subscription"
    AUTO_INDEX = "auto_index"
    AUTO_SUBSCRIPTION = "auto_subscription"


class RunMode(str, Enum):
    """Supported execution modes."""

    FORMAL = "formal"
    TEST = "test"


class StreamType(str, Enum):
    """Detected stream format."""

    TS = "ts"
    HLS = "hls"
    UNKNOWN = "unknown"


class ExitCode(IntEnum):
    """Process exit codes defined by MASTER_PLAN.md."""

    SUCCESS = 0
    INPUT_ERROR = 1
    STAGE_ERROR = 2
    PUBLISH_ERROR = 3
    PUBLISH_UNCONFIRMED = 4


# ---------------------------------------------------------------------
# Source and collection interfaces
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class SourceRecord:
    """A normalized source entry used by the source and collection stages.

    order preserves the original stable ordering within the source list.
    """

    url: str
    kind: SourceKind
    order: int
    name: Optional[str] = None


@dataclass(frozen=True)
class DownloadResult:
    """Result of one source download.

    content contains the bytes actually read, subject to the configured
    download size limit.
    """

    source: SourceRecord
    success: bool
    content: bytes = b""
    status_code: Optional[int] = None
    error: Optional[str] = None
    bytes_received: int = 0
    truncated: bool = False


@dataclass(frozen=True)
class IndexParseResult:
    """Parsed result of one downloaded source index."""

    index_source: SourceRecord
    sources: Tuple[SourceRecord, ...] = ()
    invalid_count: int = 0
    messages: Tuple[str, ...] = ()


# ---------------------------------------------------------------------
# Candidate normalization interface
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class Candidate:
    """A normalized IPTV candidate ready for validation.

    source_order and item_order preserve deterministic source and
    original-item ordering. Candidate limits are assigned before
    validation, as required by MASTER_PLAN.md.
    """

    url: str
    name: str
    source_kind: SourceKind
    source_order: int
    item_order: int
    tvg_id: Optional[str] = None
    tvg_name: Optional[str] = None
    group_title: Optional[str] = None
    source_url: Optional[str] = None


# ---------------------------------------------------------------------
# Network and validation interfaces
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class NetworkResult:
    """Bounded HTTP response information returned by network.py.

    The network layer is responsible for IPv4 and public-address checks.
    content must contain only the bytes actually read.
    """

    success: bool
    requested_url: str
    content: bytes = b""
    final_url: Optional[str] = None
    remote_ip: Optional[str] = None
    status_code: Optional[int] = None
    content_type: Optional[str] = None
    bytes_received: int = 0
    redirects: Tuple[str, ...] = ()
    error: Optional[str] = None


@dataclass(frozen=True)
class ValidationResult:
    """TS/HLS validation result for one candidate."""

    candidate: Candidate
    passed: bool
    stream_type: StreamType = StreamType.UNKNOWN
    completed: bool = True
    reason: Optional[str] = None


# ---------------------------------------------------------------------
# Filtering and publishing interfaces
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class FilterResult:
    """M3U content generated by filter.py."""

    m3u_content: str
    channel_count: int


@dataclass(frozen=True)
class PublishResult:
    """Local and Git publishing result returned to main.py."""

    success: bool
    exit_code: ExitCode
    target_path: str
    git_pushed: bool = False
    remote_verified: bool = False
    error: Optional[str] = None


# ---------------------------------------------------------------------
# Runtime reporting interfaces
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class StageResult:
    """Execution information for one pipeline stage."""

    stage_name: str
    elapsed_seconds: float
    success: bool
    incomplete: bool = False
    message: Optional[str] = None


@dataclass(frozen=True)
class RunSummary:
    """Final execution summary produced by main.py."""

    mode: RunMode
    exit_code: ExitCode
    stage_results: Tuple[StageResult, ...] = ()
    sources_attempted: int = 0
    candidates_collected: int = 0
    candidates_validated: int = 0
    candidates_passed: int = 0
    channels_published: int = 0
    incomplete: bool = False
    messages: Tuple[str, ...] = ()
